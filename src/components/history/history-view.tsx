"use client";

import { Tabs, TabsContent, TabsList, TabsTrigger } from "@/components/ui/tabs";
import { activityActionLabel, activityForOrganization, activityVisibleToRole } from "@/lib/activity";
import {
  formatJobTimestamp,
  jobOutputLabel,
  jobShortId,
  jobSourceLabel,
  jobStatusLabel,
  jobsForOrganization,
} from "@/lib/jobs";
import { relativeUsed } from "@/lib/template-library";
import { useAppStore } from "@/lib/store";
import type { LabelJob } from "@/lib/domain";
import { useMemo, useState } from "react";

function formatWhen(iso: string) {
  return relativeUsed(iso) || iso;
}

function JobDetail({ job }: { job: LabelJob }) {
  const success = job.successCount ?? job.quantity;
  const failed = job.failedCount ?? 0;
  const rows = job.rowCount ?? success + failed;
  const output = [jobOutputLabel(job.outputType), job.status === "failed" ? "Failed" : null]
    .filter(Boolean)
    .join(" · ");
  return (
    <dl className="grid grid-cols-[140px_1fr] gap-x-3 gap-y-2 text-sm">
      <dt className="text-[#5f6368]">Template</dt>
      <dd className="font-medium">{job.templateName}</dd>
      <dt className="text-[#5f6368]">Version</dt>
      <dd>
        {job.templateVersionId.startsWith("working:") ? "Draft" : "Published"} v{job.templateVersionNumber}
      </dd>
      <dt className="text-[#5f6368]">Generated by</dt>
      <dd>{job.createdByName}</dd>
      <dt className="text-[#5f6368]">Date</dt>
      <dd>{formatJobTimestamp(job.createdAt)}</dd>
      <dt className="text-[#5f6368]">Input</dt>
      <dd>
        {jobSourceLabel(job.sourceType, job.fileName)}
        {rows ? ` · ${rows} row${rows === 1 ? "" : "s"}` : ""}
      </dd>
      <dt className="text-[#5f6368]">Result</dt>
      <dd>
        {job.status === "failed"
          ? job.error || "Generation failed"
          : `${success} label${success === 1 ? "" : "s"} generated${failed ? ` · ${failed} row${failed === 1 ? "" : "s"} rejected` : ""}`}
      </dd>
      <dt className="text-[#5f6368]">Output</dt>
      <dd>{output || jobStatusLabel(job.status)}</dd>
    </dl>
  );
}

export function HistoryView({
  organizationId,
}: {
  organizationId?: string | null;
} = {}) {
  const hydrated = useAppStore((s) => s.hydrated);
  const jobs = useAppStore((s) => s.jobs);
  const activity = useAppStore((s) => s.activity);
  const currentOrgId = useAppStore((s) => s.currentOrganizationId);
  const orgId = organizationId ?? currentOrgId;
  const orgName = useAppStore((s) => s.organizations.find((item) => item.id === (organizationId ?? s.currentOrganizationId))?.name);
  const role = useAppStore((s) => s.role());
  const [selectedId, setSelectedId] = useState<string | null>(null);

  const scopedJobs = useMemo(() => (orgId ? jobsForOrganization(jobs, orgId) : []), [jobs, orgId]);
  const scopedActivity = useMemo(() => {
    const events = orgId ? activityForOrganization(activity, orgId) : [];
    return activityVisibleToRole(events, role);
  }, [activity, orgId, role]);
  const selected = scopedJobs.find((job) => job.id === selectedId) ?? null;

  if (!hydrated) {
    return <div className="flex h-full items-center justify-center text-sm text-muted-foreground">Loading…</div>;
  }

  return (
    <div className="h-full overflow-y-auto p-8">
      <h1 className="font-heading text-3xl font-semibold tracking-tight">History</h1>
      <p className="mt-1 mb-6 max-w-2xl text-sm text-muted-foreground">
        {orgName ? `${orgName} · ` : ""}Generation jobs and template activity in this workspace.
      </p>
      <Tabs defaultValue="generation">
        <TabsList>
          <TabsTrigger value="generation">Generation</TabsTrigger>
          <TabsTrigger value="activity">Activity</TabsTrigger>
        </TabsList>
        <TabsContent value="generation" className="mt-4">
          {scopedJobs.length ? (
            <div className="grid gap-4 lg:grid-cols-[minmax(0,1fr)_320px]">
              <div className="overflow-hidden rounded-xl border border-[#d0d7de] bg-white">
                <table className="w-full text-left text-sm">
                  <thead className="bg-[#f8f9fa] text-[11px] tracking-wide text-[#5f6368] uppercase">
                    <tr>
                      <th className="px-3 py-2 font-medium">Date</th>
                      <th className="px-3 py-2 font-medium">Template</th>
                      <th className="px-3 py-2 font-medium">Version</th>
                      <th className="px-3 py-2 font-medium">User</th>
                      <th className="px-3 py-2 font-medium">Quantity</th>
                      <th className="px-3 py-2 font-medium">Status</th>
                    </tr>
                  </thead>
                  <tbody>
                    {scopedJobs.map((job) => {
                      const active = job.id === selectedId;
                      return (
                        <tr
                          key={job.id}
                          className={`cursor-pointer border-t border-[#e8eaed] ${active ? "bg-[#e8f0fe]" : "hover:bg-[#f8f9fa]"}`}
                          onClick={() => setSelectedId(job.id === selectedId ? null : job.id)}
                        >
                          <td className="px-3 py-2 text-[#5f6368]">{formatWhen(job.createdAt)}</td>
                          <td className="px-3 py-2 font-medium">{job.templateName}</td>
                          <td className="px-3 py-2">v{job.templateVersionNumber}</td>
                          <td className="px-3 py-2">{job.createdByName}</td>
                          <td className="px-3 py-2">{job.successCount ?? job.quantity}</td>
                          <td className="px-3 py-2">{jobStatusLabel(job.status)}</td>
                        </tr>
                      );
                    })}
                  </tbody>
                </table>
              </div>
              <aside className="rounded-xl border border-[#d0d7de] bg-white p-4">
                {selected ? (
                  <>
                    <h2 className="mb-3 text-base font-semibold">Generation {jobShortId(selected.id)}</h2>
                    <JobDetail job={selected} />
                  </>
                ) : (
                  <p className="text-sm text-muted-foreground">Select a generation job to see template version, input, and result.</p>
                )}
              </aside>
            </div>
          ) : (
            <p className="rounded-lg border border-dashed border-border px-4 py-10 text-center text-sm text-muted-foreground">
              No generation jobs yet. Print or download a PDF to record one.
            </p>
          )}
        </TabsContent>
        <TabsContent value="activity" className="mt-4">
          {scopedActivity.length ? (
            <ul className="space-y-2">
              {scopedActivity.map((event) => (
                <li key={event.id} className="rounded-lg border border-[#e8eaed] bg-white px-3 py-2 text-sm">
                  <span className="font-medium">{event.userName || "Someone"}</span>{" "}
                  {activityActionLabel(event).toLowerCase()}{" "}
                  <span className="font-medium">“{event.templateName}”</span>
                  {event.versionNumber ? ` v${event.versionNumber}` : ""}
                  {event.labelCount ? ` · ${event.labelCount} labels` : ""}
                  <span className="block text-[11px] text-[#5f6368]">{formatWhen(event.timestamp)}</span>
                </li>
              ))}
            </ul>
          ) : (
            <p className="rounded-lg border border-dashed border-border px-4 py-10 text-center text-sm text-muted-foreground">
              No activity recorded yet.
            </p>
          )}
        </TabsContent>
      </Tabs>
    </div>
  );
}
