export const DEMO_SHOP_NAME = "Shopify Demo Store";
export const DEMO_SHOP_DOMAIN = "demo-store.labelator.local";

export function demoShopifyProductById(id: string) {
  return DEMO_SHOPIFY_PRODUCTS.find((item) => item.id === id);
}

export function demoShopifyInventory(product: DemoShopifyProduct) {
  return product.variants.reduce((sum, item) => sum + item.inventory, 0);
}

export function demoShopifyPrimaryVariant(product: DemoShopifyProduct) {
  return product.variants[0];
}

export function isDemoShopifyInStock(product: DemoShopifyProduct) {
  return demoShopifyInventory(product) > 0;
}
