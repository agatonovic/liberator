import type { DemoShopifyProduct, DemoShopifyVariant } from "./types";

function variant(
  id: string,
  title: string,
  sku: string,
  barcode: string,
  price: string,
  inventory: number,
  weight = "0.2 kg",
): DemoShopifyVariant {
  return { id, title, sku, barcode, price, inventory, weight };
}

function product(
  partial: Omit<DemoShopifyProduct, "variants"> & { variants: DemoShopifyVariant[] },
): DemoShopifyProduct {
  return partial;
}

